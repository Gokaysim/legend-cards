import type { DieType } from '../formula'
import type { DiceStyle, DieThrow } from '../schema'

/**
 * One throw as 13 numbers: the position (x, y, z), the rotation (x, y, z, w), the linear velocity (x, y, z) and the
 * angular velocity (x, y, z).
 */
type ThrowNumbers = readonly [
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
  number,
]

function throwsOf(numbers: readonly ThrowNumbers[]): DieThrow[] {
  return numbers.map(throwOf)
}

function throwOf([px, py, pz, rx, ry, rz, rw, lx, ly, lz, ax, ay, az]: ThrowNumbers): DieThrow {
  return {
    position: { x: px, y: py, z: pz },
    rotation: { x: rx, y: ry, z: rz, w: rw },
    linearVelocity: { x: lx, y: ly, z: lz },
    angularVelocity: { x: ax, y: ay, z: az },
  }
}

